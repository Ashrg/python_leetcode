# 53. 最大子数组和
# 难度：中等
# 标签：数组、动态规划
#
# 给你一个整数数组 `nums`，请你找出一个具有最大和的连续子数组（子数组最少包含一个元素），返回其最大和。
#
# 子数组是数组中的一个连续部分。
#
# ### 示例
#
# - 输入：`nums = [-2,1,-3,4,-1,2,1,-5,4]`，输出：`6`（连续子数组 `[4,-1,2,1]` 的和最大，为 6）
# - 输入：`nums = [1]`，输出：`1`
# - 输入：`nums = [5,4,-1,7,8]`，输出：`23`
#
# ### 提示
#
# - `1 <= nums.length <= 10^5`
# - `-10^4 <= nums[i] <= 10^4`
#
# ### ACM 模式输入输出格式
#
# - 输入：第一行为整数 `n`（数组长度）；第二行为 `n` 个整数（空格分隔）
# - 输出：一个整数，即最大子数组和
#
# ACM 输入示例：
# ```
# 9
# -2 1 -3 4 -1 2 1 -5 4
# ```
# 输出：`6`

def maxSubArray(nums):
    # 返回最大子数组和
    cur = best = nums[0]
    for i in nums[1:]:
        cur = max(i,i + cur)
        best = max(best, cur)
    return best
