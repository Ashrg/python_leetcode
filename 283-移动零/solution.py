# 283. 移动零
# 难度：简单
# 标签：数组、双指针
#
# 给定一个数组 `nums`，编写一个函数将所有 `0` 移动到它的末尾，同时保持非零元素的相对顺序。
#
# 请注意，必须在**不复制数组**的情况下原地对数组进行操作；函数不返回任何内容，判题时直接检查修改后的 `nums`。
#
# ### 示例
#
# - 输入：`nums = [0,1,0,3,12]`，输出：`[1,3,12,0,0]`
# - 输入：`nums = [0]`，输出：`[0]`
#
# ### 提示
#
# - `1 <= nums.length <= 10^4`
# - `-2^31 <= nums[i] <= 2^31 - 1`
#
# ### ACM 模式输入输出格式
#
# - 输入：第一行为整数 `n`（数组长度）；第二行为 `n` 个整数（空格分隔）
# - 输出：移动零之后的数组（空格分隔）
#
# ACM 输入示例：
# ```
# 5
# 0 1 0 3 12
# ```
# 输出：`1 3 12 0 0`

def moveZeroes(nums):
    # 原地修改 nums，不需要返回值
    left = 0

    for right in range(len(nums)):
        if nums[right] != 0:
            nums[left], nums[right] = nums[right],nums[left]
            left += 1
